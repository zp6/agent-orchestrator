/**
 * agent-changelog Webhook Handler
 *
 * Processes GitHub PR merge events and generates changelogs.
 * Supports free tier (template) and paid tier (LLM-powered summaries).
 *
 * Zero-touch design:
 * - GitHub App shared across fleet (users install via OAuth)
 * - Payment verified on-chain (USDC sent to fleet wallet)
 * - Changelog commits automated via GitHub App token
 */

import type { IncomingHttpHeaders } from 'http';
import { createHmac } from 'crypto';

export interface PRMergedEvent {
  action: 'closed';
  pull_request: {
    number: number;
    title: string;
    body: string;
    user: { login: string };
    labels: Array<{ name: string }>;
    merged: boolean;
    merged_at: string;
    html_url: string;
    head: { sha: string };
    base: { repo: { owner: { login: string }; name: string } };
  };
  repository: {
    owner: { login: string };
    name: string;
    full_name: string;
    default_branch: string;
  };
}

export interface ChangelogEntry {
  pr: number;
  title: string;
  labels: string[];
  author: string;
  url: string;
  mergedAt: string;
  summary?: string; // Paid tier only
  category?: 'feature' | 'fix' | 'breaking' | 'other';
}

export interface WebhookVerifyOptions {
  secret: string;
  payload: string;
  signature: string;
}

export interface ChangelogGeneratorOptions {
  isDryRun?: boolean;
  claudeApiKey?: string; // Only for paid tier
  fleetWalletAddress?: string;
  stateDb?: any; // SQLite database handle
}

/**
 * Verify GitHub webhook signature (HMAC-SHA256)
 */
export function verifyGitHubWebhookSignature({
  secret,
  payload,
  signature,
}: WebhookVerifyOptions): boolean {
  const hash = createHmac('sha256', secret)
    .update(payload)
    .digest('hex');

  const expectedSignature = `sha256=${hash}`;
  return expectedSignature === signature;
}

/**
 * Extract organization and repo from GitHub event
 */
export function extractRepoIdentifier(event: PRMergedEvent): {
  org: string;
  repo: string;
  fullName: string;
} {
  return {
    org: event.repository.owner.login,
    repo: event.repository.name,
    fullName: event.repository.full_name,
  };
}

