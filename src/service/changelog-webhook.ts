/**
 * Generate free-tier changelog entry (template-based)
 */
export function generateFreeChangelogEntry(event: PRMergedEvent): ChangelogEntry {
  const pr = event.pull_request;
  const labels = pr.labels.map((l) => l.name);

  return {
    pr: pr.number,
    title: pr.title,
    labels,
    author: pr.user.login,
    url: pr.html_url,
    mergedAt: pr.merged_at,
  };
}

/**
 * Format changelog entry as Markdown
 */
export function formatChangelogEntryAsMarkdown(entry: ChangelogEntry): string {
  const labels = entry.labels.length > 0 ? ` ${entry.labels.map((l) => `\`${l}\``).join(' ')}` : '';
  const category = entry.category ? `**${entry.category.toUpperCase()}** ` : '';

  const line = `- ${category}[#${entry.pr}](${entry.url}): ${entry.title} (@${entry.author})${labels}`;

  if (entry.summary) {
    return `${line}\n  > ${entry.summary}`;
  }
  return line;
}

/**
 * Format changelog header with fleet attribution
 */
export function formatChangelogHeader(): string {
  return `# Changelog

All notable changes to this project will be documented in this file.

**Generated by [agent-changelog](https://github.com/rapartlu/agent-changelog)** — autonomous AI fleet. See [CHARTER](https://github.com/rapartlu/agent-orchestrator/blob/main/CHARTER.md) and [treasury](https://github.com/rapartlu/agent-orchestrator/blob/main/docs/treasury.md).

---
`;
}

/**
 * Build changelog content (prepend new entry to existing)
 */
export function buildChangelogContent(
  existingContent: string | null,
  newEntry: ChangelogEntry,
  eventDate: string
): string {
  const header = formatChangelogHeader();
  const entryLine = formatChangelogEntryAsMarkdown(newEntry);

  // Extract date (YYYY-MM-DD)
  const date = eventDate.split('T')[0];

  // Create date section
  const dateSection = `## [Unreleased] - ${date}\n\n${entryLine}\n`;

  if (!existingContent || existingContent.trim().length === 0) {
    return header + dateSection;
  }

  // Remove existing header, prepend new section
  const cleaned = existingContent
    .replace(/^# Changelog.*?---\n\n/ms, '') // Remove old header
    .replace(/^---\n\n/m, ''); // Remove separator if present

  return header + dateSection + '\n' + cleaned;
}

/**
 * Handler: Process PR merge event and update changelog
 *
 * Free tier: Generate template-based changelog
 * Paid tier: Add LLM-powered summary
 */
export async function handlePRMergedEvent(
  event: PRMergedEvent,
  options: ChangelogGeneratorOptions = {}
): Promise<{
  success: boolean;
  entry: ChangelogEntry;
  isPaid: boolean;
  error?: string;
}> {
  // Only process merged PRs
  if (!event.pull_request.merged) {
    return {
      success: false,
      entry: generateFreeChangelogEntry(event),
      isPaid: false,
      error: 'PR not merged',
    };
  }

  const { org, repo } = extractRepoIdentifier(event);
  const isPaid = await isPaidRepo(org, repo, options.stateDb);

  // Generate base entry
  let entry = generateFreeChangelogEntry(event);

  // If paid, add LLM summary (stub for now)
  if (isPaid && options.claudeApiKey) {
    entry.summary = '[Premium summary would be generated here via Claude API]';
    entry.category = 'feature'; // Would be determined by LLM
  }

  // In production:
  // 1. Fetch existing CHANGELOG.md from repo
  // 2. Build new changelog content
  // 3. Commit and push via GitHub App token
  // 4. Post comment to PR
  // 5. Notify Slack/Linear if configured

  if (!options.isDryRun) {
    // Stub: Real implementation would commit to repo
    console.log(`[agent-changelog] Would update ${org}/${repo} CHANGELOG.md for PR #${entry.pr}`);
  }

  return {
    success: true,
    entry,
    isPaid,
  };
}

/**
 * Express/Node.js middleware for GitHub webhook
 *
 * Usage:
 * ```typescript
 * app.post('/github/webhook', changelogWebhookHandler(webhookSecret, options));
 * ```
 */
export function createChangelogWebhookHandler(
  webhookSecret: string,
  options: ChangelogGeneratorOptions = {}
) {
  return async (
    req: { body: PRMergedEvent; headers: IncomingHttpHeaders; rawBody?: string },
    res: { status: (code: number) => { json: (obj: any) => void } }
  ) => {
    try {
      // Verify webhook signature
      const signature = req.headers['x-hub-signature-256'] as string;
      const payload = req.rawBody || JSON.stringify(req.body);

      if (!verifyGitHubWebhookSignature({ secret: webhookSecret, payload, signature })) {
        return res.status(401).json({ error: 'Invalid signature' });
      }

      // Only process PR merge events
      if (req.headers['x-github-event'] !== 'pull_request') {
        return res.status(200).json({ ignored: 'Not a PR event' });
      }

      const event = req.body as PRMergedEvent;
      if (event.action !== 'closed' || !event.pull_request.merged) {
        return res.status(200).json({ ignored: 'PR not merged' });
      }

      // Process changelog
      const result = await handlePRMergedEvent(event, options);

      return res.status(200).json({
        success: result.success,
        entry: result.entry,
        isPaid: result.isPaid,
      });
    } catch (error) {
      console.error('[agent-changelog] Webhook error:', error);
      return res.status(500).json({ error: 'Internal server error' });
    }
  };
}

